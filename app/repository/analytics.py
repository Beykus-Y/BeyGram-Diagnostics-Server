"""Minimal installation analytics. No Telegram identifiers are ever persisted here."""

from __future__ import annotations

import hashlib
import hmac
import sqlite3
from datetime import UTC, datetime, timedelta

from ..repository import allowlist


def token_digest(token: str) -> str:
    """Stable digest of a client-generated random 256-bit credential.

    Installation credentials must outlive rotations of report NONCE_PEPPER.
    A domain-separated SHA-256 digest is safe for high-entropy random secrets.
    """
    return hashlib.sha256(b"beygram-install-credential-v1:" + token.encode("ascii")).hexdigest()


def beta_status(conn: sqlite3.Connection, account_count: int, user_ids: list[int] | None) -> str:
    """Unknown if TDLib did not provide the entire account list."""
    if account_count == 0 or user_ids is None or len(set(user_ids)) != account_count:
        return "unknown"
    return "approved" if any(allowlist.is_active(conn, uid) for uid in user_ids) else "not_approved"


def upsert(
    conn: sqlite3.Connection,
    *,
    installation_id: str,
    digest: str,
    revision: int,
    version: str,
    version_code: int,
    channel: str,
    android_version: str,
    device_model: str | None,
    account_count: int,
    user_ids: list[int] | None,
    at: float,
) -> tuple[bool, bool, str]:
    """Returns created, accepted (new revision), effective beta status.

    A token is generated by the client and stored BEFORE its first network
    attempt. Its digest protects first-request retries without a bot handshake.
    """
    row = conn.execute(
        "SELECT * FROM analytics_installations WHERE installation_id=?", (installation_id,)
    ).fetchone()
    if row is not None and not hmac.compare_digest(row["token_hash"], digest):
        raise PermissionError("installation token mismatch")

    if row is not None and revision < row["sync_revision"]:
        return False, False, _effective_status(row, at)

    status = beta_status(conn, account_count, user_ids)
    checked = at if status != "unknown" else None
    if row is None:
        conn.execute(
            """INSERT INTO analytics_installations (
                installation_id, token_hash, sync_revision, first_seen_at, last_seen_at,
                app_version, app_version_code, release_channel, android_version,
                device_model, account_count, beta_status, last_beta_checked_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (installation_id, digest, revision, at, at, version, version_code, channel,
             android_version, device_model, account_count, status, checked),
        )
        created, changed, accepted = True, True, True
    elif revision > row["sync_revision"]:
        changed = (row["app_version"], row["app_version_code"], row["release_channel"]) != (
            version, version_code, channel
        )
        conn.execute(
            """UPDATE analytics_installations SET
                sync_revision=?, last_seen_at=?, app_version=?, app_version_code=?,
                release_channel=?, android_version=?, device_model=?, account_count=?,
                beta_status=?, last_beta_checked_at=?
               WHERE installation_id=?""",
            (revision, at, version, version_code, channel, android_version,
             device_model, account_count, status, checked, installation_id),
        )
        created, accepted = False, True
    else:
        # Idempotent replay. Do not overwrite state or create duplicate history.
        return False, False, _effective_status(row, at)

    if changed:
        conn.execute(
            """INSERT INTO analytics_versions
                (installation_id, app_version, app_version_code, release_channel, recorded_at)
                VALUES (?, ?, ?, ?, ?)""",
            (installation_id, version, version_code, channel, at),
        )
    day = datetime.fromtimestamp(at, UTC).date().isoformat()
    conn.execute(
        "INSERT OR IGNORE INTO analytics_activity_days (installation_id, day) VALUES (?, ?)",
        (installation_id, day),
    )
    return created, accepted, status


def _effective_status(row: sqlite3.Row, at: float) -> str:
    checked = row["last_beta_checked_at"]
    if checked is None or checked < at - 86400:
        return "unknown"
    return row["beta_status"]


def erase(conn: sqlite3.Connection, installation_id: str, digest: str) -> bool:
    row = conn.execute(
        "SELECT token_hash FROM analytics_installations WHERE installation_id=?", (installation_id,)
    ).fetchone()
    if row is None or not hmac.compare_digest(row["token_hash"], digest):
        return False
    conn.execute("DELETE FROM analytics_installations WHERE installation_id=?", (installation_id,))
    return True


def prune(conn: sqlite3.Connection, *, at: float, retention_days: int) -> int:
    cutoff = at - retention_days * 86400
    result = conn.execute("DELETE FROM analytics_installations WHERE last_seen_at < ?", (cutoff,))
    # Old activity days are not needed after the active-installation retention window.
    day_cutoff = (datetime.fromtimestamp(at, UTC) - timedelta(days=retention_days)).date().isoformat()
    conn.execute("DELETE FROM analytics_activity_days WHERE day < ?", (day_cutoff,))
    return result.rowcount


def dashboard(conn: sqlite3.Connection, *, at: float) -> dict:
    last_day, last_week, last_month = at - 86400, at - 7 * 86400, at - 30 * 86400
    row = conn.execute(
        """SELECT COUNT(*) total,
                  SUM(CASE WHEN last_seen_at>=? THEN 1 ELSE 0 END) dau,
                  SUM(CASE WHEN last_seen_at>=? THEN 1 ELSE 0 END) wau,
                  SUM(CASE WHEN last_seen_at>=? THEN 1 ELSE 0 END) mau,
                  SUM(CASE WHEN first_seen_at>=? THEN 1 ELSE 0 END) new_30d,
                  SUM(account_count) account_slots
             FROM analytics_installations""",
        (last_day, last_week, last_month, last_month),
    ).fetchone()
    beta_rows = conn.execute(
        """SELECT CASE WHEN last_beta_checked_at IS NULL OR last_beta_checked_at < ?
                        THEN 'unknown' ELSE beta_status END AS status,
                  COUNT(*) AS count
           FROM analytics_installations GROUP BY status""",
        (last_day,),
    ).fetchall()
    result = {key: int(row[key] or 0) for key in (
        "total", "dau", "wau", "mau", "new_30d", "account_slots"
    )}
    result["beta"] = {r["status"]: r["count"] for r in beta_rows}
    result["versions"] = [
        dict(r) for r in conn.execute(
            """SELECT app_version AS name, COUNT(*) AS count
               FROM analytics_installations GROUP BY app_version ORDER BY count DESC LIMIT 12"""
        )
    ]
    result["channels"] = [
        dict(r) for r in conn.execute(
            """SELECT release_channel AS name, COUNT(*) AS count
               FROM analytics_installations GROUP BY release_channel ORDER BY count DESC"""
        )
    ]
    result["android"] = [
        dict(r) for r in conn.execute(
            """SELECT android_version AS name, COUNT(*) AS count
               FROM analytics_installations GROUP BY android_version ORDER BY count DESC LIMIT 12"""
        )
    ]
    result["daily"] = [
        dict(r) for r in conn.execute(
            """SELECT day, COUNT(*) AS count FROM analytics_activity_days
                WHERE day >= ? GROUP BY day ORDER BY day""",
            (datetime.fromtimestamp(last_month, UTC).date().isoformat(),),
        )
    ]
    return result


def recent_updates(conn: sqlite3.Connection, limit: int = 30) -> list[dict]:
    """Actual version transitions, not initial installs or replayed syncs."""
    return [
        dict(row) for row in conn.execute(
            """SELECT installation_id, previous_version, current_version, recorded_at
               FROM (
                 SELECT installation_id,
                        app_version || ' (' || app_version_code || ')' AS current_version,
                        LAG(app_version || ' (' || app_version_code || ')') OVER
                          (PARTITION BY installation_id ORDER BY id) AS previous_version,
                        recorded_at
                   FROM analytics_versions
               )
               WHERE previous_version IS NOT NULL AND previous_version != current_version
               ORDER BY recorded_at DESC LIMIT ?""",
            (limit,),
        )
    ]


def installations(
    conn: sqlite3.Connection, *, at: float, status: str, channel: str, version: str,
    page: int, page_size: int = 25,
) -> tuple[list[dict], int]:
    conditions, args = [], []
    effective = """CASE WHEN last_beta_checked_at IS NULL OR last_beta_checked_at < ?
                   THEN 'unknown' ELSE beta_status END"""
    if status in {"approved", "not_approved", "unknown"}:
        conditions.append(effective + " = ?")
        args.extend([at - 86400, status])
    if channel in {"stable", "dev"}:
        conditions.append("release_channel = ?")
        args.append(channel)
    if version:
        conditions.append("app_version = ?")
        args.append(version[:40])
    where = " WHERE " + " AND ".join(conditions) if conditions else ""
    total = conn.execute(
        "SELECT COUNT(*) FROM analytics_installations" + where, args
    ).fetchone()[0]
    rows = conn.execute(
        "SELECT installation_id, app_version, release_channel, android_version, "
        "device_model, account_count, first_seen_at, last_seen_at, " + effective + " AS beta_status "
        "FROM analytics_installations" + where +
        " ORDER BY last_seen_at DESC LIMIT ? OFFSET ?",
        [at - 86400, *args, page_size, (page - 1) * page_size],
    ).fetchall()
    return [dict(row) for row in rows], total
